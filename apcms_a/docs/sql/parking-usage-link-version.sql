-- 실제 업무 행의 버전 증가/연결 해제 시험은 별도이며 서버 해제 플래그는 변경하지 않음.
-- 이미 적용된 DB에는 ALTER를 재실행하지 않는다.
-- Oracle 11g/21c용 검토·승인 후 수동 적용 SQL. DDL은 암묵적 커밋됨.
-- 배포 순서: 전체 사용처 확인 → 쓰기 중단/백업 → DDL·트리거 검증 → Boot 플래그 활성화.
-- 기존 연결에는 버전 0을 부여하며 새 MATCH 성공 응답을 받은 뒤에만 AI 해제 가능.
-- 1. 적용 전 조회: 대상 테이블·컬럼·같은 이름 트리거 존재 여부를 먼저 확인한다.
-- 조회 결과를 확인하지 않고 DDL 구간까지 일괄 실행하지 않는다. 재실행용 멱등 스크립트가 아니다.
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME = 'PARKING_USAGE';
SELECT COLUMN_NAME, DATA_TYPE, DATA_PRECISION, NULLABLE, DATA_DEFAULT
  FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'PARKING_USAGE' AND COLUMN_NAME = 'LINK_VERSION';
SELECT TRIGGER_NAME, STATUS FROM USER_TRIGGERS
 WHERE TABLE_NAME = 'PARKING_USAGE';

-- 2. 별도 DB 변경 승인 후 적용할 DDL 구간.
ALTER TABLE PARKING_USAGE ADD (LINK_VERSION NUMBER(18,0) DEFAULT 0 NOT NULL);
ALTER TABLE PARKING_USAGE ADD CONSTRAINT CK_PUSAGE_LINK_VERSION CHECK (LINK_VERSION >= 0);

CREATE OR REPLACE TRIGGER TRG_PUSAGE_LINK_VERSION
BEFORE INSERT OR UPDATE ON PARKING_USAGE
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        :NEW.LINK_VERSION := 0;
    ELSIF (:OLD.PARKING_SPACE_ID != :NEW.PARKING_SPACE_ID
           OR (:OLD.PARKING_SPACE_ID IS NULL AND :NEW.PARKING_SPACE_ID IS NOT NULL)
           OR (:OLD.PARKING_SPACE_ID IS NOT NULL AND :NEW.PARKING_SPACE_ID IS NULL))
       OR (:OLD.PARKING_RESERVATION_ID != :NEW.PARKING_RESERVATION_ID
           OR (:OLD.PARKING_RESERVATION_ID IS NULL AND :NEW.PARKING_RESERVATION_ID IS NOT NULL)
           OR (:OLD.PARKING_RESERVATION_ID IS NOT NULL AND :NEW.PARKING_RESERVATION_ID IS NULL))
       OR (:OLD.EXIT_AT != :NEW.EXIT_AT
           OR (:OLD.EXIT_AT IS NULL AND :NEW.EXIT_AT IS NOT NULL)
           OR (:OLD.EXIT_AT IS NOT NULL AND :NEW.EXIT_AT IS NULL))
       OR (:OLD.VEHICLE_NUMBER != :NEW.VEHICLE_NUMBER
           OR (:OLD.VEHICLE_NUMBER IS NULL AND :NEW.VEHICLE_NUMBER IS NOT NULL)
           OR (:OLD.VEHICLE_NUMBER IS NOT NULL AND :NEW.VEHICLE_NUMBER IS NULL)) THEN
        :NEW.LINK_VERSION := :OLD.LINK_VERSION + 1;
    ELSE
        -- 같은 연결을 유지하는 조회성 갱신은 세대를 바꾸지 않는다.
        :NEW.LINK_VERSION := :OLD.LINK_VERSION;
    END IF;
END;
