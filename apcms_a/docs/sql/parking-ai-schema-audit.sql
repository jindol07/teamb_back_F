-- 업무 행 조회/변경, NEXTVAL, DDL, COMMIT, FOR UPDATE를 실행하지 않는다.
-- SQLGate에서 실제 AWS 연결을 선택하고 연결 정보를 확인한 뒤 실행한다.
-- 로컬 코드 검사 결과이며 실제 배포 코드·기능 플래그는 별도 확인해야 한다.

-- 1. 접속 대상과 Oracle 버전
SELECT USER AS SESSION_USER,
       SYS_CONTEXT('USERENV', 'DB_NAME') AS DB_NAME,
       SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS SERVICE_NAME,
       SYS_CONTEXT('USERENV', 'SERVER_HOST') AS SERVER_HOST
  FROM DUAL;
SELECT PRODUCT, VERSION FROM PRODUCT_COMPONENT_VERSION WHERE PRODUCT LIKE 'Oracle%';

-- 2. 이용·예약·점유·판정 기록의 기본 테이블
SELECT TABLE_NAME FROM USER_TABLES
 WHERE TABLE_NAME IN ('VEHICLE', 'PARKING_USAGE', 'PARKING_RESERVATION',
                      'PARKING_FLOOR', 'PARKING_ZONE', 'PARKING_SPACE',
                      'PARKING_SPACE_HISTORY', 'AI_DETECTION_EVENT',
                      'SAFETY_INCIDENT', 'NOTIFICATION')
 ORDER BY TABLE_NAME;

-- 3. 실제 컬럼 정의. 코드가 요구하는 컬럼·형식과 대조한다.
SELECT TABLE_NAME, COLUMN_ID, COLUMN_NAME, DATA_TYPE, DATA_LENGTH,
       DATA_PRECISION, DATA_SCALE, NULLABLE, DATA_DEFAULT
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME IN ('PARKING_USAGE', 'PARKING_RESERVATION', 'PARKING_SPACE',
                      'PARKING_SPACE_HISTORY', 'AI_DETECTION_EVENT', 'SAFETY_INCIDENT', 'NOTIFICATION')
 ORDER BY TABLE_NAME, COLUMN_ID;

-- 4. LINK_VERSION은 로컬 코드상 space-release-enabled=true 경로에서 요구된다.
-- 기본 false 경로와 구분하며, 컬럼 누락만으로 일반 입출차 실패를 단정하지 않는다.
SELECT COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE, NULLABLE, DATA_DEFAULT
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME = 'PARKING_USAGE' AND COLUMN_NAME = 'LINK_VERSION';
SELECT CONSTRAINT_NAME, STATUS, VALIDATED, SEARCH_CONDITION
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME = 'PARKING_USAGE' AND CONSTRAINT_NAME = 'CK_PUSAGE_LINK_VERSION';
SELECT TRIGGER_NAME, STATUS, TRIGGERING_EVENT, TRIGGER_TYPE
  FROM USER_TRIGGERS WHERE TABLE_NAME = 'PARKING_USAGE';
SELECT OBJECT_NAME, STATUS FROM USER_OBJECTS
 WHERE OBJECT_TYPE = 'TRIGGER' AND OBJECT_NAME = 'TRG_PUSAGE_LINK_VERSION';
SELECT LINE, TEXT FROM USER_SOURCE
 WHERE TYPE = 'TRIGGER' AND NAME = 'TRG_PUSAGE_LINK_VERSION' ORDER BY LINE;
SELECT NAME, TYPE, LINE, POSITION, TEXT FROM USER_ERRORS
 WHERE NAME = 'TRG_PUSAGE_LINK_VERSION' ORDER BY SEQUENCE;

-- 5. 주차 이벤트의 저장·이력 생성에 필요한 시퀀스. NEXTVAL은 호출하지 않는다.
SELECT SEQUENCE_NAME, INCREMENT_BY, CACHE_SIZE
  FROM USER_SEQUENCES
 WHERE SEQUENCE_NAME IN ('SEQ_PARKING_USAGE', 'SEQ_AI_DETECTION_EVENT', 'SEQ_PARKING_SPACE_HISTORY')
 ORDER BY SEQUENCE_NAME;

-- 6. 이벤트 중복 보호와 사고 그룹 컬럼의 실제 인덱스 구성을 확인한다.
SELECT I.TABLE_NAME, I.INDEX_NAME, I.UNIQUENESS, I.STATUS,
       C.COLUMN_POSITION, C.COLUMN_NAME
  FROM USER_INDEXES I JOIN USER_IND_COLUMNS C ON C.INDEX_NAME = I.INDEX_NAME
 WHERE I.TABLE_NAME IN ('AI_DETECTION_EVENT', 'SAFETY_INCIDENT')
 ORDER BY I.TABLE_NAME, I.INDEX_NAME, C.COLUMN_POSITION;
